def search(query: str) -> list[dict]:
    """
    Search the FAQ database for entries matching the given query.
    """
    return index.search(
        query,
        num_results=5,
        boost_dict={"question": 5.0, "answer": 10.0, "section": 0.2},
        filter_dict={"course": "llm-zoomcamp"}
    )

